"""Adapter for company ATS boards: Greenhouse, Lever, Ashby, SmartRecruiters,
Oracle, Eightfold, IBM, Jibe and Workday (see workday_api.py).

These are official, public, no-auth JSON APIs. Boards are listed in
data/ats_boards.yaml (generated by scripts/discover_ats_boards.py). Titles
are pre-filtered to intern/co-op here so a 2,000-role board doesn't flood
the pipeline; the per-user role filter still runs afterwards.
"""

from __future__ import annotations

import datetime as dt
import json
import logging
import time
from collections.abc import Callable
from pathlib import Path

import httpx
import yaml

from ..models import Job
from ..normalize import infer_terms, split_locations, strip_html, strip_tracking
from ..paths import DATA_ROOT as DATA_ROOT
from ..paths import ROOT as ROOT
from . import eightfold, jibe, listing_http
from . import ibm_careers as ibm
from . import oracle_cx as oracle
from . import smartrecruiters_api as sr
from . import workday_api as wd
from .base import Adapter, fetch_text

log = logging.getLogger(__name__)

INTERN_RE = listing_http.INTERN_RE

JD_MAX_CHARS = 20000  # full JD; late qualification sections score double

_API = {
    "greenhouse": "https://boards-api.greenhouse.io/v1/boards/{slug}/jobs",
    "lever": "https://api.lever.co/v0/postings/{slug}?mode=json",
    "ashby": "https://api.ashbyhq.com/posting-api/job-board/{slug}",
}

# ATSes whose board needs several requests (paged keyword search). Each lister
# returns the raw pages; every page goes through parse() like a one-shot board.
_LISTERS: dict[str, Callable[[httpx.Client, dict], list[str]]] = {
    "smartrecruiters": sr.fetch_pages,
    "oracle": oracle.fetch_pages,
    "eightfold": eightfold.fetch_pages,
    "ibm": ibm.fetch_pages,
    "jibe": jibe.fetch_pages,
}


def _lever_jd(j: dict) -> str | None:
    """Lever splits the JD: intro in descriptionPlain, the requirement
    bullets (where degree/clearance demands live) in `lists`, closing
    boilerplate in additionalPlain."""
    parts = [j.get("descriptionPlain") or ""]
    for section in j.get("lists") or []:
        parts.append(section.get("text") or "")
        parts.append(strip_html(section.get("content") or ""))
    parts.append(j.get("additionalPlain") or "")
    text = " ".join(p for p in parts if p).strip()
    return text or None


def _iso_date(value: str | None) -> dt.date | None:
    if not value:
        return None
    try:
        return dt.datetime.fromisoformat(value.replace("Z", "+00:00")).date()
    except ValueError:
        return None


def board_id(board: dict) -> str:
    """Identity of an ats_boards.yaml row for first-sight seeding:
    "<ats>:<slug>", slug lower-cased so a case-only edit is not a new board.
    parse() stamps it on every Job (so every lister routed through parse gets
    it), and fetch() records each board that answered in fetched_boards. An
    adapter outside this class that serves several boards must do both:
    `job.board = board_id(row)` and
    `self.fetched_boards[board_id(row)] = bool(row.get("backfill"))`.
    A board's rows must be its COMPLETE listing: a lister whose page fails
    or hits its page cap short of the end must raise (no rows for that board
    this run), never return what it has. A partial first answer would be
    seeded as the whole backlog and its tail delivered later as news."""
    return f"{board['ats']}:{str(board['slug']).lower()}"


def local_boards_path(boards_file: str, data_root: Path | None = None) -> Path:
    """The instance overlay for a template boards file:
    data/ats_boards.yaml -> DATA_ROOT/data/ats_boards.local.yaml."""
    rel = Path(boards_file)
    return (data_root or DATA_ROOT) / rel.with_name(f"{rel.stem}.local{rel.suffix}")


def load_boards(boards_file: str, *, root: Path | None = None,
                data_root: Path | None = None) -> list[dict]:
    """Template boards (code checkout) followed by the instance's optional
    overlay (same schema, gitignored in the template) -- boards an instance
    derived from its own history stay out of the public template. A row the
    template already lists (ats and slug compared case-insensitively) is
    not repeated; `ats` is normalized to lower case."""
    rows = list(yaml.safe_load(
        ((root or ROOT) / boards_file).read_text(encoding="utf-8"))["boards"])
    local = local_boards_path(boards_file, data_root)
    if local.exists():
        extra = (yaml.safe_load(local.read_text(encoding="utf-8")) or {})
        rows += extra.get("boards") or []
    seen: set[tuple[str, str]] = set()
    out = []
    for row in rows:
        if isinstance(row.get("ats"), str):   # "Workday" -> "workday"
            row = {**row, "ats": row["ats"].strip().casefold()}
        key = (str(row.get("ats")), str(row.get("slug")).casefold())
        if key not in seen:
            seen.add(key)
            out.append(row)
    return out


def board_problems(boards: list[dict]) -> list[str]:
    """Rows that cannot be polled: missing fields or a malformed workday
    slug. config_check reports them; at run time such a row fails alone."""
    problems = []
    for i, row in enumerate(boards):
        label = f"board #{i + 1} ({row.get('company') or '?'})"
        missing = [k for k in ("company", "ats", "slug") if not row.get(k)]
        if missing:
            problems.append(f"{label}: missing {', '.join(missing)}")
            continue
        if row["ats"] == "workday":
            try:
                wd.split_slug(str(row["slug"]))
            except ValueError as exc:
                problems.append(f"{label}: {exc}")
    return problems


class AtsBoardsAdapter(Adapter):
    def fetch(self, client: httpx.Client, today: dt.date) -> list[Job]:
        boards = load_boards(self.cfg.boards_file or "data/ats_boards.yaml")
        jobs: list[Job] = []
        failures = 0
        wd_raw = wd.fetch_listings(str(b.get("slug")) for b in boards
                                   if b.get("ats") == "workday")
        for board in boards:
            started = time.monotonic()
            try:
                path = f"{board['ats']}:{board['slug']}:{board['company']}"
                lister = _LISTERS.get(board["ats"])
                if board["ats"] == "workday":   # prefetched, 4 tenants at a time
                    pages = [wd.listing(wd_raw, str(board["slug"]))]
                elif lister:
                    pages = lister(client, board)
                else:
                    pages = [fetch_text(
                        client, _API[board["ats"]].format(slug=board["slug"]))]
                parsed = [job for raw in pages
                          for job in self.parse(raw, path, today)]
            except Exception as exc:  # noqa: BLE001 - one board never kills the source
                failures += 1
                log.warning("ats board %s/%s failed after %.1fs: %s",
                            board.get("ats"), board.get("slug"),
                            time.monotonic() - started, exc)
                continue
            elapsed = time.monotonic() - started
            if board["ats"] in _LISTERS:
                log.info("ats board %s/%s: %d intern posting(s) in %.1fs",
                         board["ats"], board["slug"], len(parsed), elapsed)
            self.fetched_boards[board_id(board)] = bool(board.get("backfill"))
            jobs.extend(parsed)
        log.info("source %s: %d intern postings from %d boards (%d failed)",
                 self.cfg.name, len(jobs), len(boards), failures)
        return jobs

    def parse(self, raw: str, path: str, today: dt.date) -> list[Job]:
        """path is '{ats}:{slug}:{company}' -- keeps the base-class contract
        so the per-ATS parsers are testable against fixtures without network.
        Lever/Ashby ship the JD inline; Greenhouse lists carry no content, so
        those jobs get a jd_url for main.enrich_jds to fetch lazily."""
        ats, slug, company = path.split(":", 2)
        data = json.loads(raw)
        # Annotated so the per-ATS builders share one row shape
        # (title, url, location, date_posted, description, jd_url) instead of
        # widening to `object` on the join of three differently-typed lambdas.
        builders: dict[str, Callable[[], list[tuple]]] = {
            "greenhouse": lambda: [
                (j.get("title"), j.get("absolute_url"),
                 (j.get("location") or {}).get("name", ""),
                 _iso_date(j.get("first_published") or j.get("updated_at")),
                 None,
                 _API["greenhouse"].format(slug=slug) + f"/{j['id']}"
                 if j.get("id") else None)
                for j in data.get("jobs", [])],
            "lever": lambda: [
                (j.get("text"), j.get("hostedUrl"),
                 (j.get("categories") or {}).get("location", ""),
                 dt.datetime.fromtimestamp(j["createdAt"] / 1000,
                                           tz=dt.UTC).date()
                 if j.get("createdAt") else None,
                 _lever_jd(j), None)
                for j in data if isinstance(j, dict)],
            "ashby": lambda: [
                (j.get("title"), j.get("jobUrl"),
                 " / ".join(filter(None, [j.get("location")] + [
                     s.get("location") for s in j.get("secondaryLocations") or []])),
                 _iso_date(j.get("publishedAt")),
                 (j.get("descriptionPlain")
                  or strip_html(j.get("descriptionHtml") or "") or None),
                 None)
                for j in data.get("jobs", []) if j.get("isListed", True)],
            "smartrecruiters": lambda: [
                (j.get("name"), sr.posting_url(j, slug),
                 sr.location_str(j),
                 _iso_date(j.get("releasedDate")),
                 None,
                 sr.DETAIL_URL.format(slug=slug, posting_id=j["id"])
                 if j.get("id") else None)
                for j in data.get("content", [])],
            "oracle": lambda: oracle.rows(data, slug),
            "eightfold": lambda: eightfold.rows(data, slug),
            "ibm": lambda: ibm.rows(data, slug),
            "jibe": lambda: jibe.rows(data, slug),
            "workday": lambda: [
                (j.get("title"), wd.public_url(slug, j["externalPath"]),
                 wd.location_str(j),
                 wd.posted_date(j.get("postedOn"), today),
                 None,
                 wd.detail_url(slug, j["externalPath"]))
                for j in data.get("jobPostings", []) if j.get("externalPath")],
        }
        rows = builders[ats]()

        jobs: list[Job] = []
        for title, url, location, date_posted, description, jd_url in rows:
            if not title or not url or not INTERN_RE.search(title):
                continue
            terms, confidence = infer_terms(title, today)
            jobs.append(Job(
                company=company,
                title=title.strip(),
                locations=split_locations(location or ""),
                terms=terms,
                term_confidence=confidence,
                url=strip_tracking(url),
                date_posted=date_posted,
                description=description[:JD_MAX_CHARS] if description else None,
                jd_url=jd_url,
                source=self.cfg.name,
                board=board_id({"ats": ats, "slug": slug}),
            ))
        if ats == "workday":
            wd.set_work_models(jobs, data, slug)
        return jobs
